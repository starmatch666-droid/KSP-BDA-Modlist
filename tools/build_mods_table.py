def main() -> None:
    rows = list(csv.DictReader(CSV.open(encoding="utf-8-sig")))
    rows.sort(key=lambda row: (CATEGORY_ORDER.index(row["category"]), row["folder"].lower()))
    missing = [row["folder"] for row in rows if row["folder"] not in NAMES]
    if missing:
        print("Missing Chinese names:")
        for folder in missing:
            print(" ", folder)
        raise SystemExit(1)

    lines = [
        "# 当前模组中英对照表",
        "",
        f"共 {len(rows)} 个 GameData 顶层目录；按类别排序。",
        "",
        "| 英文名 | 中文名 | 作用简述 |",
        "|---|---|---|",
    ]
    for row in rows:
        english = row["title"]
        if re.search(r"[\u4e00-\u9fff]", english):
            english = row["folder"]
        purpose = row["purpose"].replace("|", "\\|")
        lines.append(f"| {english} | {NAMES[row['folder']]} | {purpose} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} with {len(rows)} rows")


if __name__ == "__main__":
    main()
